/// Index of a symbol in the registry.
#[inline]
pub fn sym(name: &str) -> i64 {
    SYMBOLS
        .iter()
        .position(|s| *s == name)
        .map(|idx| idx as i64)
        .unwrap_or_else(|| panic!("symbol '{name}' not in registry"))
}

/// Try to lookup the symbol index if it exists in the registry.
#[inline]
pub fn try_sym(name: &str) -> Option<i64> {
    SYMBOLS.iter().position(|s| *s == name).map(|idx| idx as i64)
}

/// Reverse-lookup a symbol name from its integer index.
#[inline]
pub fn sym_name(id: i64) -> Option<&'static str> {
    usize::try_from(id).ok().and_then(|idx| SYMBOLS.get(idx)).copied()
}
